$(document).ready(function(){

    $(".mobile-menu-btn").on("click", function(e){
        e.preventDefault();
        e.stopPropagation();

        $(".nav-links").toggleClass("active");
    });

    $(".dropdown > a").on("click", function(e){
        if($(window).width() <= 992){
            e.preventDefault();
            e.stopPropagation();

            let parent = $(this).parent();

            $(".dropdown").not(parent).removeClass("active");
            $(".sub-dropdown").removeClass("active");

            parent.toggleClass("active");
        }
    });

    $(".sub-dropdown > a").on("click", function(e){
        if($(window).width() <= 992){
            e.preventDefault();
            e.stopPropagation();

            let parent = $(this).parent();

            $(".sub-dropdown").not(parent).removeClass("active");
            parent.toggleClass("active");
        }
    });

    $(document).on("click", function(e){
        if($(window).width() <= 992){
            if(!$(e.target).closest(".nav-wrapper").length){
                $(".nav-links").removeClass("active");
                $(".dropdown").removeClass("active");
                $(".sub-dropdown").removeClass("active");
            }
        }
    });

});
</script>